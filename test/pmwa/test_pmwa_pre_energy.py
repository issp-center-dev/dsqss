"""End-to-end check of the std.in -> pmwa_pre -> pmwa_H chain.

The energy that pmwa_H reports for the input generated by pmwa_pre from
data/pmwa_pre_energy/std.in is compared with the exact energy of the
Hamiltonian that std.in describes,

    H = sum_<ij> [ -Jz Sz_i Sz_j - Jxy (Sx_i Sx_j + Sy_i Sy_j) ]
        - h sum_i Sz_i - Gamma sum_i Sx_i,

where the transverse field acts in the frame after the sublattice rotation
that pmwa_pre applies for antiferromagnetic Jxy (t = |Jxy|).  This pins down
the conversion done by pmwa_pre (t = |Jxy|, v = Jz, mu = h, g = Gamma / 2),
which an earlier version got wrong by a factor of four (issues #22, #35).
"""

import glob
import os
import subprocess
import sys
import unittest

import numpy as np
import scipy.stats as stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from exact_energy import hamiltonian, thermal_averages  # noqa: E402

ALPHA = 0.01

# the model written in data/pmwa_pre_energy/std.in
STDIN = {
    "Jxy": -1.0,
    "Jz": -1.0,
    "Gamma": 0.4,
    "h": 0.2,
    "L": [6],
    "beta": 4.0,
    "nset": 10,
}


def read_result(filename):
    res = {}
    with open(filename) as f:
        for line in f:
            words = line.split()
            if len(words) >= 5 and words[0] == "R" and words[2] == "=":
                res[words[1]] = (float(words[3]), float(words[4]))
    return res


def p_value(X, E, N, Y):
    t = (X - Y) / E
    return 2 * stats.t.cdf(-np.abs(t), N - 1)


class Test_PMWA_PRE_ENERGY(unittest.TestCase):
    def setUp(self):
        self.cwd = os.getcwd()
        self.datadir = os.path.join(self.cwd, "data", "pmwa_pre_energy")
        build = os.path.join(self.cwd, "..", "..")
        self.bindir = os.path.abspath(os.path.join(build, "src", "pmwa"))
        # the pmwa_pre wrapper of the build tree puts the dsqss package on sys.path
        self.pmwa_pre = os.path.abspath(os.path.join(build, "tool", "pmwa_pre"))
        os.chdir(self.datadir)
        # leftovers of an earlier run would make pmwa_H restart from them
        patterns = ("param.in", "lattice.xml", "sample.log.*", "*evout_sample.log*")
        for pattern in patterns:
            for fname in glob.glob(pattern):
                os.remove(fname)

    def tearDown(self):
        os.chdir(self.cwd)

    def test_energy_matches_exact(self):
        self.assertEqual(
            0,
            subprocess.call(
                [sys.executable, self.pmwa_pre, "-g", self.bindir, "std.in"]
            ),
        )
        self.assertEqual(
            0,
            subprocess.call(
                ["mpiexec", "-np", "1", os.path.join(self.bindir, "pmwa_H"), "param.in"]
            ),
        )
        X, E = read_result("sample.log.0")["ene"]

        _, H, number = hamiltonian(
            "spin",
            STDIN["L"],
            t=abs(STDIN["Jxy"]),
            v=STDIN["Jz"],
            g=0.5 * STDIN["Gamma"],
            mu=STDIN["h"],
        )
        ene, _ = thermal_averages(H, number, STDIN["beta"])
        Y = ene / np.prod(STDIN["L"])

        p = p_value(X, E, STDIN["nset"], Y)
        print(
            "ene: X={0}, E={1}, Y={2}, t={3}, p={4}".format(X, E, Y, (X - Y) / E, p)
        )
        self.assertGreaterEqual(p, ALPHA)


if __name__ == "__main__":
    unittest.main()
